var groupEventOverrides = map[string]map[string]string{}

type SoundDefinition struct {
	ID   int    `json:"id"`
	Name string `json:"name"`
}

type GenSound struct {
	PascalName string
	ID         int
	Name       string
}

type GenGroup struct {
	PascalName string
	Index      int
	Sounds     [5]int
	Has        uint8
}

type SoundTemplateData struct {
	Sounds     []GenSound
	MaxSoundID int
	Groups     []GenGroup
}

func generateSounds(rawSounds io.ReadCloser, data map[string]any) error {
	const (
		outputFile = "internal/mc/sound/sound_gen.go"
		tmplFile   = "cmd/gen-prismarine-js/tmpl/sounds.tmpl"
	)

	var soundDefs []SoundDefinition
	if err := json.NewDecoder(rawSounds).Decode(&soundDefs); err != nil {
		return err
	}

	maxID := 0
	processed := make([]GenSound, len(soundDefs))
	soundIDByName := make(map[string]int, len(soundDefs))
	for i, s := range soundDefs {
		if s.ID > maxID {
			maxID = s.ID
		}
		processed[i] = GenSound{
			PascalName: toPascalCase(s.Name) + "ID",
			ID:         s.ID,
			Name:       s.Name,
		}
		soundIDByName[s.Name] = s.ID
	}

	seen := map[string]bool{}
	var groupNames []string
	for _, g := range blockToGroup {
		if g == "none" || seen[g] {
			continue
		}
		seen[g] = true
		groupNames = append(groupNames, g)
	}
	sort.Strings(groupNames)

	groups := make([]GenGroup, 0, len(groupNames)+1)
	groups = append(groups, GenGroup{PascalName: "NoGroup", Index: 0})

	for i, gname := range groupNames {
		gg := GenGroup{
			PascalName: toPascalCase(gname) + "Group",
			Index:      i + 1,
		}
		for ei, ev := range canonicalEvents {
			name := fmt.Sprintf("block.%s.%s", gname, ev)
			if override, ok := groupEventOverrides[gname][ev]; ok {
				name = override
			}
			if id, ok := soundIDByName[name]; ok {
				gg.Sounds[ei] = id
				gg.Has |= 1 << ei
			}
		}
		if gg.Has == 0 {
			return fmt.Errorf("sound group %q has no canonical events; add a groupEventOverrides entry", gname)
		}
		groups = append(groups, gg)
	}

	outFile, err := os.Create(outputFile)
	if err != nil {
		return err
	}
	defer outFile.Close()

	tmpl, err := template.ParseFiles(tmplFile)
	if err != nil {
		return fmt.Errorf("failed to parse template: %w", err)
	}

	if err := tmpl.Execute(outFile, SoundTemplateData{Sounds: processed, MaxSoundID: maxID, Groups: groups}); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	pascalByGroup := map[string]string{"none": "NoGroup"}
	for _, gname := range groupNames {
		pascalByGroup[gname] = toPascalCase(gname) + "Group"
	}
	blockGroupPascal := make(map[string]string, len(blockToGroup))
	for b, g := range blockToGroup {
		blockGroupPascal[b] = pascalByGroup[g]
	}
	data["sounds"] = soundDefs
	data["blockGroupPascal"] = blockGroupPascal
	return nil
}
